def main():
    os.makedirs(OUT, exist_ok=True)
    diseases = []
    for name, code, *rest in TOKUTEI:
        diseases.append(dict(name=name, icd10=code, tokutei=True))
    seen = {d["name"] for d in diseases}
    for name, code in DISEASES:
        if name in seen:
            continue
        seen.add(name)
        diseases.append(dict(name=name, icd10=code, tokutei=False))

    payload = {
        "departments": dict(label="診療科", entries=[dict(name=n) for n in DEPARTMENTS]),
        "diseases": dict(label="傷病名（ICD-10）", entries=diseases),
        "body_sites": dict(label="部位", entries=[dict(name=n) for n in BODY_SITES]),
        "infections": dict(label="感染症", entries=[dict(name=n) for n in INFECTIONS]),
        "clinic_suffix": dict(label="医療機関", entries=[dict(name=n) for n in CLINIC_SUFFIX]),
        "prefectures": dict(label="都道府県", entries=[dict(name=n) for n in PREFECTURES]),
    }
    for key, val in payload.items():
        with open(os.path.join(OUT, f"{key}.json"), "w", encoding="utf-8") as fp:
            json.dump(val, fp, ensure_ascii=False, indent=1)
        print(f"  dict/{key}.json  {len(val['entries'])} 件")
    with open(os.path.join(OUT, "field_map.json"), "w", encoding="utf-8") as fp:
        json.dump(FIELD_DICTIONARY, fp, ensure_ascii=False, indent=1)
    print(f"  dict/field_map.json  {len(FIELD_DICTIONARY)} 項目")


if __name__ == "__main__":
    main()
