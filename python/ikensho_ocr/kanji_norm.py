# 数字・記号のよくある誤認
DIGIT_MAP = {
    "О": "0", "Ｏ": "0", "ｌ": "1", "Ｉ": "1", "｜": "1",
    "－": "-", "―": "-", "‐": "-", "ー": "-",
}


def normalize_variants(text: str) -> str:
    """簡体字・異体字を日本語字体に置き換える。"""
    if not text:
        return text
    return "".join(VARIANT_MAP.get(ch, ch) for ch in text)


def normalize_digits(text: str) -> str:
    if not text:
        return text
    return "".join(DIGIT_MAP.get(ch, ch) for ch in text)


def clean_ocr(text: str) -> str:
    """OCR 生出力の共通後処理。"""
    if not text:
        return ""
    text = normalize_variants(text)
    # 罫線や括弧だけの読み取りは無意味なので落とす
    stripped = text.strip()
    if stripped and all(ch in "()（）［］[]{}｛｝|｜/\\_—―‐-・.,、。 　:：;；" for ch in stripped):
        return ""
    return stripped
